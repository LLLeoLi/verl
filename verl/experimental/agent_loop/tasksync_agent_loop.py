"""Agent loop for task-sync style environments.

Ported from verl 0.7.0 to 0.7.1:
  - AgentLoopBase now receives ``dataset_cls`` / ``data_config`` via ``**kwargs``.
  - Uses ``self.apply_chat_template`` from the base class (handles executor dispatch).
  - ``@rollout_trace_op`` wraps ``run`` so traces line up with the other loops.

task-sync envs differ from GEM planning envs in several key ways:
  - File structure: data.py + env.py + prompt.md
  - Database: SQLite file generated by running data.py
  - Env class: Task_Env(db_path, workspace) -- plain Python class, no gem.core.Env
  - Tools and env are combined in one class (env.tools dict)
  - step() returns (reward, info) -- 2-tuple
  - Prompt comes from a separate prompt.md file
  - Evaluation is workspace-file-based (claim_done triggers env.step)
"""
